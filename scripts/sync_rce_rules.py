#!/usr/bin/env python3
"""Write Java's RceCore.java from aiwaf-rust's rce.rs, so both check the same text.

The rules, the Log4j un-nesting patterns and the HTML entity table are copied from rce.rs;
the rest of RceCore.java is the Java form of the same steps. Run it after changing rce.rs:

    python scripts/sync_rce_rules.py          # rewrites RceCore.java
    python scripts/sync_rce_rules.py --check  # exits 1 if RceCore.java is out of date
"""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
RUST = ROOT / "rust" / "crates" / "aiwaf_core" / "src" / "rce.rs"
JAVA = ROOT / "java" / "src" / "main" / "java" / "com" / "aiwaf" / "core" / "RceCore.java"


def java_string(pattern: str) -> str:
    # Rust's ASCII word boundary is Java's default one.
    pattern = pattern.replace("(?-u:\\b)", "\\b")
    return '"' + pattern.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n") + '"'


def read_rust(source: str) -> dict:
    block = source[source.index("// RULES START"):source.index("// RULES END")]
    rules = re.findall(r'rule\(\s*"(\w+)",\s*r(#?)"(.*?)"\2\s*,?\s*\)', block, re.S)
    if not rules:
        raise SystemExit("No rules found in rce.rs")
    regex = lambda name: re.search(rf"let {name} = \w+\.get_or_init\(\|\| \{{?\s*Regex::new\(r\"(.*?)\"\)", source, re.S).group(1)
    entities = re.findall(r'\("(\w+)", \'(\\\\|\\\'|.)\'\)', source[source.index("const ENTITIES"):source.index("];", source.index("const ENTITIES"))])
    return {
        "rules": [(name, pattern) for name, _hash, pattern in rules],
        "nested": regex("nested"),
        "date": regex("date"),
        "lookup": regex("lookup"),
        "entities": [(name, value.replace("\\\\", "\\").replace("\\'", "'")) for name, value in entities],
    }


def render(parts: dict) -> str:
    rules = ",\n".join(f"            Map.entry({java_string(name)}, Pattern.compile({java_string(pattern)}))"
                       for name, pattern in parts["rules"])
    entities = ", ".join(f"Map.entry({java_string(name)}, {java_string(value)})" for name, value in parts["entities"])
    return f'''package com.aiwaf.core;

import java.nio.charset.CharacterCodingException;
import java.nio.charset.CodingErrorAction;
import java.nio.charset.StandardCharsets;
import java.nio.ByteBuffer;
import java.util.List;
import java.util.Map;
import java.util.regex.Matcher;
import java.util.regex.Pattern;

/**
 * Remote code execution signatures, checked in every request value the payload check reads.
 *
 * <p>Generated by scripts/sync_rce_rules.py from aiwaf-rust's rce.rs, so both match the same
 * text; run it after changing rce.rs. See rce.rs for what each rule matches. A value is checked
 * as sent, then with escapes, entities, fullwidth and invisible characters undone, then as base64.
 */
public final class RceCore {{
    private static final int MAX_CHARS = 16384;
    private static final List<Map.Entry<String, Pattern>> RULES = List.of(
{rules});
    private static final Pattern NESTED = Pattern.compile({java_string(parts["nested"])});
    private static final Pattern DATE = Pattern.compile({java_string(parts["date"])});
    private static final Pattern LOOKUP = Pattern.compile({java_string(parts["lookup"])});
    private static final Map<String, String> ENTITIES = Map.ofEntries({entities});

    private RceCore() {{}}

    /** A Log4j lookup, after undoing the nesting used to hide it, as in ${{${{lower:j}}ndi:ldap://x}}. */
    static boolean jndi(String value) {{
        if (!value.contains("${{")) return false;
        String text = value;
        for (int pass = 0; pass < 8; pass++) {{
            String next = DATE.matcher(NESTED.matcher(text).replaceAll("$1")).replaceAll("$1");
            if (next.equals(text)) break;
            text = next;
        }}
        return LOOKUP.matcher(text).find();
    }}

    private static String check(String text) {{
        if (jndi(text)) return "rce_jndi_lookup";
        for (Map.Entry<String, Pattern> rule : RULES) {{
            if (rule.getValue().matcher(text).find()) return rule.getKey();
        }}
        return null;
    }}

    private static boolean isHex(String text) {{
        return !text.isEmpty() && text.chars().allMatch(c -> Character.digit(c, 16) >= 0);
    }}

    private static void appendCode(StringBuilder out, int code) {{
        if (Character.isValidCodePoint(code)) out.appendCodePoint(code);
    }}

    /** The value with escapes, entities, fullwidth and invisible characters undone, or null. */
    static String normalize(String text) {{
        if (text.chars().noneMatch(c -> c == '\\\\' || c == '&' || c == '%' || c >= 0x80)) return null;
        int[] chars = text.codePoints().toArray();
        StringBuilder out = new StringBuilder(text.length());
        int i = 0;
        while (i < chars.length) {{
            int c = chars[i];
            int next = i + 1 < chars.length ? chars[i + 1] : -1;
            if ((c == '\\\\' || c == '%') && (next == 'u' || next == 'U')) {{
                if (c == '\\\\' && i + 2 < chars.length && chars[i + 2] == '{{') {{
                    int end = -1;
                    for (int k = i + 3; k < Math.min(chars.length, i + 10); k++) if (chars[k] == '}}') {{ end = k; break; }}
                    String digits = end < 0 ? "" : new String(chars, i + 3, end - i - 3);
                    if (end >= 0 && isHex(digits)) {{ appendCode(out, Integer.parseInt(digits, 16)); i = end + 1; continue; }}
                }} else if (i + 6 <= chars.length && isHex(new String(chars, i + 2, 4))) {{
                    appendCode(out, Integer.parseInt(new String(chars, i + 2, 4), 16));
                    i += 6;
                    continue;
                }}
            }}
            if (c == '\\\\' && (next == 'x' || next == 'X') && i + 4 <= chars.length && isHex(new String(chars, i + 2, 2))) {{
                appendCode(out, Integer.parseInt(new String(chars, i + 2, 2), 16));
                i += 4;
                continue;
            }}
            if (c == '&') {{
                int end = -1;
                for (int k = i + 1; k < Math.min(chars.length, i + 13); k++) if (chars[k] == ';') {{ end = k; break; }}
                if (end >= 0) {{
                    String body = new String(chars, i + 1, end - i - 1);
                    String decoded = null;
                    try {{
                        if (body.startsWith("#x") || body.startsWith("#X")) {{
                            int code = Integer.parseInt(body.substring(2), 16);
                            if (Character.isValidCodePoint(code)) decoded = new String(Character.toChars(code));
                        }} else if (body.startsWith("#")) {{
                            int code = Integer.parseInt(body.substring(1));
                            if (Character.isValidCodePoint(code)) decoded = new String(Character.toChars(code));
                        }} else {{
                            decoded = ENTITIES.get(body);
                        }}
                    }} catch (NumberFormatException ex) {{
                        decoded = null;
                    }}
                    if (decoded != null) {{ out.append(decoded); i = end + 1; continue; }}
                }}
            }}
            if (c >= 0xFF01 && c <= 0xFF5E) {{
                out.appendCodePoint(c - 0xFEE0);
            }} else if (c != 0x200B && c != 0x200C && c != 0x200D && c != 0x2060 && c != 0xFEFF && c != 0x00AD) {{
                out.appendCodePoint(c);
            }}
            i++;
        }}
        String result = out.toString();
        return result.equals(text) ? null : result;
    }}

    /** The bytes a whole-value base64 string holds, or null. */
    static byte[] base64Bytes(String text) {{
        String value = text.strip();
        if (value.length() < 16 || value.length() > MAX_CHARS || value.length() % 4 == 1) return null;
        int bits = 0;
        int count = 0;
        ByteBuffer bytes = ByteBuffer.allocate(value.length() * 3 / 4 + 3);
        for (int k = 0; k < value.length(); k++) {{
            char b = value.charAt(k);
            int digit;
            if (b >= 'A' && b <= 'Z') digit = b - 'A';
            else if (b >= 'a' && b <= 'z') digit = b - 'a' + 26;
            else if (b >= '0' && b <= '9') digit = b - '0' + 52;
            else if (b == '+' || b == '-') digit = 62;
            else if (b == '/' || b == '_') digit = 63;
            else if (b == '=') break;
            else return null;
            bits = (bits << 6) | digit;
            count += 6;
            if (count >= 8) {{
                count -= 8;
                bytes.put((byte) (bits >> count));
                bits &= (1 << count) - 1;
            }}
        }}
        byte[] result = new byte[bytes.position()];
        bytes.flip().get(result);
        return result;
    }}

    /** Text that decodes as UTF-8 and is mostly readable, or null. */
    static String readableText(byte[] bytes) {{
        String decoded;
        try {{
            decoded = StandardCharsets.UTF_8.newDecoder().onMalformedInput(CodingErrorAction.REPORT)
                    .onUnmappableCharacter(CodingErrorAction.REPORT).decode(ByteBuffer.wrap(bytes)).toString();
        }} catch (CharacterCodingException ex) {{
            return null;
        }}
        long total = decoded.codePoints().count();
        long readable = decoded.codePoints().filter(c -> !Character.isISOControl(c) || Character.isWhitespace(c)).count();
        return readable * 10 >= total * 9 ? decoded : null;
    }}

    /** A zlib header: deflate with a window of at most 32 KB and a valid check value, as in 78 9C. */
    static boolean zlibHeader(byte[] raw) {{
        if (raw.length < 2) return false;
        int a = raw[0] & 0xff;
        int b = raw[1] & 0xff;
        return (a & 0x0f) == 8 && (a >> 4) <= 7 && ((a << 8) | b) % 31 == 0;
    }}

    /** A gzip or zlib stream inflated to at most limit bytes, or null when the bytes aren't one. */
    public static byte[] inflate(byte[] raw, int limit) {{
        boolean gzip = raw.length >= 2 && (raw[0] & 0xff) == 0x1f && (raw[1] & 0xff) == 0x8b;
        if (!gzip && !zlibHeader(raw)) return null;
        try (java.io.InputStream in = gzip
                ? new java.util.zip.GZIPInputStream(new java.io.ByteArrayInputStream(raw))
                : new java.util.zip.InflaterInputStream(new java.io.ByteArrayInputStream(raw))) {{
            return in.readNBytes(limit);
        }} catch (java.io.IOException ex) {{
            return null;
        }}
    }}

    /** A base64 value checked for what it holds, unwrapped up to three layers deep. */
    static String base64Layers(String text, int layers) {{
        byte[] bytes = base64Bytes(text);
        if (bytes == null) return null;
        String rule = classifyBinary(bytes);
        if (rule != null) return rule;
        byte[] inflated = inflate(bytes, MAX_CHARS * 4);
        if (inflated != null) {{
            if ((rule = classifyBinary(inflated)) != null) return rule;
            bytes = inflated;
        }}
        String decoded = readableText(bytes);
        if (decoded == null) return null;
        String normalized = normalize(decoded);
        if ((rule = check(decoded)) != null) return rule;
        if (normalized != null && (rule = check(normalized)) != null) return rule;
        return layers > 1 ? base64Layers(normalized != null ? normalized : decoded, layers - 1) : null;
    }}

    /** Bytes at least one of which every rule needs, as in aiwaf-rust's TRIGGERS. */
    private static final String TRIGGERS = "()[]{{}}<>$!\\"'%#@._|:=/-;&\\n\\r`\\\\";
    private static final List<String> SERIALIZED_PREFIXES = List.of("rO0AB", "aced0005", "gASV", "AAEAAAD");
    private static final List<String> DOCUMENT_MARKERS = List.of(
            "@type", "$type", "__type", "dataSourceName", "<java", "<object", "<sorted-set", "<dynamic-proxy",
            "java.beans", "<%", "<?", "[\\"", "\\\\u");

    /** False when no rule can match the value: a cheap scan that saves running the rules. */
    static boolean mayMatch(String text) {{
        for (int i = 0; i < text.length(); i++) {{
            char c = text.charAt(i);
            if (c >= 0x80 || TRIGGERS.indexOf(c) >= 0) return true;
        }}
        String start = text.stripLeading();
        return SERIALIZED_PREFIXES.stream().anyMatch(start::startsWith);
    }}

    /** The check for a whole JSON or XML document, when it has a marker of an attack in its shape. */
    public static String classifyDocument(String text) {{
        if (text == null || DOCUMENT_MARKERS.stream().noneMatch(text::contains)) return null;
        return classify(text);
    }}

    /** Returns the rule for a value that carries remote code execution, or null. */
    public static String classify(String value) {{
        if (value == null || value.isEmpty()) return null;
        String text = value.length() > MAX_CHARS ? value.substring(0, MAX_CHARS) : value;
        String rule;
        String normalized = null;
        if (mayMatch(text)) {{
            rule = check(text);
            if (rule != null) return rule;
            normalized = normalize(text);
            if (normalized != null && (rule = check(normalized)) != null) return rule;
        }}
        // Base64 has none of the trigger bytes, so it's decoded and checked whatever the scan found.
        return base64Layers(normalized != null ? normalized : text, 3);
    }}

    /** Rules checked in an uploaded file's content: code a server runs, as in <?php in an image. */
    private static final List<String> UPLOAD_RULES = List.of("rce_php", "rce_webshell");

    /** The rule for an uploaded file's content: a binary object, or PHP, JSP or ASP code in its first 16 KB. */
    public static String classifyUpload(byte[] content) {{
        String rule = classifyBinary(content);
        if (rule != null) return rule;
        String text = new String(content, 0, Math.min(content.length, MAX_CHARS), StandardCharsets.UTF_8);
        if (text.indexOf('<') < 0 && text.indexOf('$') < 0 && text.indexOf('(') < 0) return null;
        for (Map.Entry<String, Pattern> entry : RULES) {{
            if (UPLOAD_RULES.contains(entry.getKey()) && entry.getValue().matcher(text).find()) return entry.getKey();
        }}
        return null;
    }}

    /** The rule for a raw binary serialized object: Java, pickle, .NET BinaryFormatter, Ruby Marshal. */
    public static String classifyBinary(byte[] raw) {{
        int start = 0;
        while (start < raw.length && (raw[start] == ' ' || (raw[start] >= 9 && raw[start] <= 13))) start++;
        int n = raw.length - start;
        boolean found = startsWith(raw, start, 0xac, 0xed, 0x00, 0x05)
                || (n >= 8 && (raw[start] & 0xff) == 0x80 && raw[start + 1] >= 2 && raw[start + 1] <= 5)
                || startsWith(raw, start, 0x00, 0x01, 0x00, 0x00, 0x00, 0xff, 0xff, 0xff, 0xff);
        if (!found && startsWith(raw, start, 0x04, 0x08)) {{
            String head = new String(raw, start, Math.min(n, 256), StandardCharsets.ISO_8859_1);
            found = head.contains("o:") || head.contains("Gem::");
        }}
        return found ? "rce_serialized_object" : null;
    }}

    private static boolean startsWith(byte[] raw, int start, int... prefix) {{
        if (raw.length - start < prefix.length) return false;
        for (int k = 0; k < prefix.length; k++) if ((raw[start + k] & 0xff) != prefix[k]) return false;
        return true;
    }}

    /** True for a field name that reaches an object's prototype, as in __proto__ or a[constructor][prototype]. */
    public static boolean pollutingKey(String name) {{
        if (name == null || (!name.contains("__proto__") && !name.contains("prototype"))) return false;
        List<String> parts = java.util.Arrays.stream(name.split("[\\\\[\\\\].]")).filter(p -> !p.isEmpty()).toList();
        if (parts.contains("__proto__")) return true;
        for (int k = 0; k + 1 < parts.size(); k++) {{
            if (parts.get(k).equals("constructor") && parts.get(k + 1).equals("prototype")) return true;
        }}
        return false;
    }}

    private static byte[] decodeBytes(String text) {{
        byte[] raw = text.getBytes(StandardCharsets.UTF_8);
        ByteBuffer out = ByteBuffer.allocate(raw.length);
        for (int k = 0; k < raw.length; k++) {{
            int a = k + 2 < raw.length ? Character.digit(raw[k + 1], 16) : -1;
            int b = a >= 0 ? Character.digit(raw[k + 2], 16) : -1;
            if (raw[k] == '%' && a >= 0 && b >= 0) {{
                out.put((byte) (a * 16 + b));
                k += 2;
            }} else {{
                out.put(raw[k] == '+' ? (byte) ' ' : raw[k]);
            }}
        }}
        byte[] result = new byte[out.position()];
        out.flip().get(result);
        return result;
    }}

    /**
     * Checks each field of a query string or form body on its own, so a rule anchored to the
     * start of a value, as in data=rO0AB..., a binary value and a prototype key are found.
     */
    public static String classifyFields(String text) {{
        if (text == null || (text.indexOf('&') < 0 && text.indexOf('=') < 0)) return null;
        String[] fields = text.split("&", -1);
        for (int k = 0; k < Math.min(fields.length, 1024); k++) {{
            int eq = fields[k].indexOf('=');
            String name = eq < 0 ? fields[k] : fields[k].substring(0, eq);
            String value = eq < 0 ? "" : fields[k].substring(eq + 1);
            if (pollutingKey(new String(decodeBytes(name), StandardCharsets.UTF_8))) return "rce_prototype_pollution";
            byte[] raw = decodeBytes(value);
            String rule = classifyBinary(raw);
            if (rule == null) rule = classify(new String(raw, StandardCharsets.UTF_8));
            if (rule != null) return rule;
        }}
        return null;
    }}
}}
'''


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--check", action="store_true", help="Exit 1 if RceCore.java is out of date.")
    args = parser.parse_args(argv)
    generated = render(read_rust(RUST.read_text(encoding="utf-8")))
    if args.check:
        if JAVA.read_text(encoding="utf-8") != generated:
            print("RceCore.java is out of date: run python scripts/sync_rce_rules.py", file=sys.stderr)
            return 1
        return 0
    JAVA.write_text(generated, encoding="utf-8")
    print(f"Wrote {JAVA}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
